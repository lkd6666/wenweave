"""Emit the current SQLAlchemy metadata as a data-free MySQL schema."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateIndex, CreateTable


BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

import app.models  # noqa: F401  Register every model before reading metadata.
from app.db.base import Base


def mysql_schema() -> str:
    """Compile DDL directly from models, without connecting to a database."""
    dialect = mysql.dialect()
    statements = [
        "-- Generated by backend/scripts/export_mysql_schema.py. Do not edit by hand.",
        "-- This file intentionally contains schema only: no INSERT statements or secrets.",
        "SET NAMES utf8mb4;",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "",
    ]

    def compile_statement(statement: object) -> str:
        # SQLAlchemy's MySQL compiler pads some column lines before a newline.
        # Strip that generated whitespace so the committed schema passes diff checks.
        rendered = str(statement.compile(dialect=dialect))  # type: ignore[attr-defined]
        return "\n".join(line.rstrip() for line in rendered.splitlines()).rstrip() + ";"

    for table in Base.metadata.sorted_tables:
        statements.append(compile_statement(CreateTable(table)))
        for index in sorted(table.indexes, key=lambda item: item.name or ""):
            statements.append(compile_statement(CreateIndex(index)))
        statements.append("")

    statements.append("SET FOREIGN_KEY_CHECKS = 1;")
    statements.append("")
    return "\n".join(statements)


def main() -> int:
    parser = argparse.ArgumentParser(description="Export the application MySQL DDL without data")
    parser.add_argument("--output", type=Path, required=True, help="Destination .sql file")
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(mysql_schema(), encoding="utf-8", newline="\n")
    print(f"MySQL schema written to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
